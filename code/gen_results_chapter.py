def kalpha_grid_table(path: Path, exp_letter: str, scope: str,
                      label: str, exp_title: str, kcl: int,
                      enc_pair_str: str, caption_extras: str = "") -> str:
    df = pd.read_csv(path)
    sub = df[df.scope == scope]
    if sub.empty:
        return ""
    Ks = sorted(sub.K.unique())
    alphas = sorted(sub.alpha.unique())
    n_alpha = len(alphas)
    scope_word = "aggregate" if scope == "aggregate" else "held-out"
    lines = [
        r"\begin{table}[!ht]",
        r"\centering",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\textwidth}{!}{%",
        r"\begin{tabular}{l " + " ".join(["ccc"] * n_alpha) + r"}",
        r"\toprule",
    ]
    top = "      "
    for a in alphas:
        top += f" & \\multicolumn{{3}}{{c}}{{$\\alpha = {a:.1f}$}}"
    lines.append(top + r" \\")
    rule_parts = []
    for i in range(n_alpha):
        lo = 2 + 3 * i
        hi = lo + 2
        rule_parts.append(f"\\cmidrule(lr){{{lo}-{hi}}}")
    lines.append("        " + " ".join(rule_parts))
    metric_hdr = "$K$"
    for _ in alphas:
        metric_hdr += " & $R@10$ & NMI & $r$"
    lines.append(metric_hdr + r" \\")
    lines.append(r"\midrule")
    for K in Ks:
        cells = [str(K)]
        for a in alphas:
            r = sub[(sub.K == K) & (sub.alpha == a)]
            if r.empty:
                cells.extend([r"\textemdash"] * 3)
                continue
            r = r.iloc[0]
            cells.extend([fmt(r["R@10"]), fmt(r["nmi"]), fmt(r["pearson_r"])])
        lines.append(" & ".join(cells) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"}")
    cap = (
        f"Experiment~{exp_title}: $K \\times \\alpha$ grid at "
        f"\\textbf{{{scope_word}}} scope, evaluated at "
        f"{enc_pair_str}. Each $(K, \\alpha)$ cell reports $R@10$ / NMI "
        f"(uncorrected) / Pearson $r$; $K_{{\\mathrm{{cl}}}} = {kcl}$. "
        f"{caption_extras}"
    )
    lines.append(f"\\caption{{{cap}}}")
    lines.append(f"\\label{{{label}}}")
    lines.append(r"\end{table}")
    return "\n".join(lines)


def reference_pair_table(grid_csv: Path, exp_name: str, exp_title: str,
                         scopes: list[tuple[str, str]], label: str,
                         operating_point_desc: str) -> str:
    """Two reference pairs side by side for one recipe.

    `scopes` is a list of (scope_in_csv, display_label) tuples.
    """
    df = pd.read_csv(grid_csv)
    rows = []
    for pair_label, img_enc, aud_enc, role in [
        (r"CLIP-L/14 $\times$ CLAP-unfused", PAIR_CANON[0], PAIR_CANON[1], "text-aligned"),
        (r"DINOv2-large $\times$ MERT-330m", PAIR_FREE[0],  PAIR_FREE[1],  "text-free"),
    ]:
        for scope, scope_disp in scopes:
            sub = df[(df.experiment == exp_name) & (df.scope == scope)
                     & (df.image_encoder == img_enc)
                     & (df.audio_encoder == aud_enc)]
            if sub.empty:
                continue
            r = sub.iloc[0]
            rows.append({
                "pair": pair_label, "role": role, "scope": scope_disp,
                "R@10": r["R@10"], "nmi": r["nmi"], "r": r["pearson_r"],
            })
    if not rows:
        return ""

    n_scopes = len(scopes)
    lines = [
        r"\begin{table}[!ht]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{l l " + " ".join(["ccc"] * n_scopes) + r"}",
        r"\toprule",
    ]
    top = r"Encoder pair & Role"
    for _, sd in scopes:
        top += f" & \\multicolumn{{3}}{{c}}{{{sd}}}"
    lines.append(top + r" \\")
    rule_parts = []
    base = 3  # after pair, role
    for i in range(n_scopes):
        lo = base + 3 * i
        hi = lo + 2
        rule_parts.append(f"\\cmidrule(lr){{{lo}-{hi}}}")
    lines.append("        " + " ".join(rule_parts))
    sub_hdr = r" & "
    for _ in scopes:
        sub_hdr += r" & $R@10$ & NMI & $r$"
    lines.append(sub_hdr + r" \\")
    lines.append(r"\midrule")
    seen = []
    for r in rows:
        if r["pair"] in seen:
            continue
        seen.append(r["pair"])
        row_cells = [r["pair"], r["role"]]
        for scope_in_csv, _ in scopes:
            cell = next((x for x in rows
                         if x["pair"] == r["pair"]
                         and df[(df.experiment == exp_name)
                                & (df.image_encoder == (PAIR_CANON[0] if "CLIP" in r["pair"] else PAIR_FREE[0]))
                                & (df.audio_encoder == (PAIR_CANON[1] if "CLIP" in r["pair"] else PAIR_FREE[1]))
                                & (df.scope == scope_in_csv)].shape[0] > 0
                         and x["scope"] == dict(scopes)[scope_in_csv]),
                        None)
            if cell is None:
                row_cells.extend([r"\textemdash"] * 3)
            else:
                row_cells.extend([fmt(cell["R@10"]), fmt(cell["nmi"]), fmt(cell["r"])])
        lines.append(" & ".join(row_cells) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    cap = (
        f"Experiment~{exp_title} at the two reference encoder pairs, "
        f"{operating_point_desc}. $R@10$ / NMI (uncorrected) / Pearson "
        f"$r$ per (pair, scope) cell. The CLIP--CLAP pair is the "
        f"contrastively-text-aligned default; the DINOv2--MERT pair has "
        f"no encoder--text alignment, providing the methodologically "
        f"cleaner ground for unsupervised claims."
    )
    lines.append(f"\\caption{{{cap}}}")
    lines.append(f"\\label{{{label}}}")
    lines.append(r"\end{table}")
    return "\n".join(lines)


def top_n_table(grid_csv: Path, exp_name: str, scope: str, exp_title: str,
                scope_disp: str, label: str, n: int = 8) -> str:
    df = pd.read_csv(grid_csv)
    sub = df[(df.experiment == exp_name) & (df.scope == scope)]
    sub = sub.dropna(subset=["R@10"])
    if sub.empty:
        return ""
    top = sub.sort_values("R@10", ascending=False).head(n)
    lines = [
        r"\begin{table}[!ht]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{r l l c c c}",
        r"\toprule",
        r"Rank & Image encoder & Audio encoder & $R@10$ & NMI & Pearson $r$ \\",
        r"\midrule",
    ]
    for rank, (_, r) in enumerate(top.iterrows(), start=1):
        row = [
            str(rank),
            r["image_encoder"], r["audio_encoder"],
            fmt(r["R@10"]), fmt(r["nmi"]), fmt(r["pearson_r"]),
        ]
        if rank == 1:
            row = [r"\textbf{" + c + r"}" for c in row]
        lines.append(" & ".join(row) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    cap = (
        f"Experiment~{exp_title}: top {n} encoder pairs by $R@10$ at "
        f"{scope_disp} scope. Each row is a single $(f_X, f_Y)$ "
        f"configuration evaluated at the recipe's canonical operating "
        f"point. The top row (bold) is the configuration optimum."
    )
    lines.append(f"\\caption{{{cap}}}")
    lines.append(f"\\label{{{label}}}")
    lines.append(r"\end{table}")
    return "\n".join(lines)


def single_row_table(rows: list[dict], label: str, caption: str,
                     columns: list[tuple[str, str]]) -> str:
    """rows: list of dicts; columns: list of (key, header_string) tuples."""
    lines = [
        r"\begin{table}[!ht]",
        r"\centering",
        r"\small",
        r"\begin{tabular}{l " + "c " * (len(columns) - 1) + "c" + r"}",
        r"\toprule",
        " & ".join(h for _, h in columns) + r" \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(" & ".join(
            row[k] if isinstance(row[k], str) else fmt(row[k])
            for k, _ in columns
        ) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(f"\\caption{{{caption}}}")
    lines.append(f"\\label{{{label}}}")
    lines.append(r"\end{table}")
    return "\n".join(lines)


def cross_method_summary() -> str:
    df = pd.read_csv(RES / "exp_grid" / "sweep.csv")
    methods = [
        ("c-direct", "C-direct (supervised, $K=300$)", "heldout"),
        ("d",        "D (caption-cost FGW)",           "heldout"),
        ("unsup",    "Pure-GW",                        "heldout"),
        ("text",     "Text-only (cosine)",             "heldout"),
    ]
    rows = []
    for exp, title, scope in methods:
        cells_canon = df[(df.experiment == exp) & (df.scope == scope)
                         & (df.image_encoder == PAIR_CANON[0])
                         & (df.audio_encoder == PAIR_CANON[1])]
        cells_free  = df[(df.experiment == exp) & (df.scope == scope)
                         & (df.image_encoder == PAIR_FREE[0])
                         & (df.audio_encoder == PAIR_FREE[1])]
        best = df[(df.experiment == exp) & (df.scope == scope)
                  ].dropna(subset=["R@10"]).sort_values("R@10", ascending=False).head(1)
        rows.append({
            "method": title,
            "canon_R10": cells_canon["R@10"].iloc[0] if not cells_canon.empty else float("nan"),
            "canon_nmi": cells_canon["nmi"].iloc[0]  if not cells_canon.empty else float("nan"),
            "free_R10":  cells_free["R@10"].iloc[0]  if not cells_free.empty  else float("nan"),
            "free_nmi":  cells_free["nmi"].iloc[0]   if not cells_free.empty  else float("nan"),
            "best_R10":  best["R@10"].iloc[0]        if not best.empty        else float("nan"),
            "best_pair": f"{best['image_encoder'].iloc[0]} $\\times$ {best['audio_encoder'].iloc[0]}"
                         if not best.empty else r"\textemdash",
        })
    lines = [
        r"\begin{table}[!ht]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{l cc cc cl}",
        r"\toprule",
        r"      & \multicolumn{2}{c}{CLIP $\times$ CLAP}"
        r"      & \multicolumn{2}{c}{DINOv2 $\times$ MERT}"
        r"      & \multicolumn{2}{c}{Configuration optimum} \\",
        r"        \cmidrule(lr){2-3} \cmidrule(lr){4-5} \cmidrule(lr){6-7}",
        r"Method & $R@10$ & NMI & $R@10$ & NMI & $R@10$ & Best pair \\",
        r"\midrule",
    ]
    for r in rows:
        lines.append(
            " & ".join([
                r["method"],
                fmt(r["canon_R10"]), fmt(r["canon_nmi"]),
                fmt(r["free_R10"]),  fmt(r["free_nmi"]),
                fmt(r["best_R10"]),  r["best_pair"],
            ]) + r" \\"
        )
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(
        r"\caption{Cross-method summary at the two reference encoder pairs "
        r"and at each recipe's configuration optimum. $R@10$ and NMI "
        r"reported on the held-out / same-rows partition (100 rows). "
        r"NMI is uncorrected; the chance floor at $n=100$, "
        r"$K_{\mathrm{cl}}=15$ is approximately $0.36$, so absolute NMI "
        r"values across pairs should be read against this floor.}"
    )
    lines.append(r"\label{tab:cross-method-summary}")
    lines.append(r"\end{table}")
    return "\n".join(lines)


