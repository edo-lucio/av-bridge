PAIR_CANON = ("clip-large", "clap-unfused")
PAIR_FREE  = ("dinov2-large", "mert-330m")


def fmt(v) -> str:
    return r"\textemdash" if (v is None or pd.isna(v)) else f"{float(v):.3f}"


def fig(path: str, caption: str, label: str, width: str = r"\linewidth",
        placement: str = "ht") -> str:
    """Emit a `\\begin{figure}` block. If the image file does not exist on
    disk we still emit the float with a commented-out \\includegraphics line
    plus a placeholder hint, so the host LaTeX compiles cleanly while
    making clear which PNG is missing."""
    abs_path = ROOT / path
    if abs_path.exists():
        graphics_line = f"\\includegraphics[width={width}]{{{path}}}"
    else:
        graphics_line = (f"% \\includegraphics[width={width}]{{{path}}}\n"
                         f"\\fbox{{\\parbox[c][2cm][c]{{0.7\\linewidth}}{{"
                         f"\\centering \\small \\itshape "
                         f"figure pending: \\texttt{{{path}}}}}}}")
    return "\n".join([
        f"\\begin{{figure}}[{placement}]",
        r"\centering",
        graphics_line,
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\end{figure}",
    ])


def fig_pair(path_left: str, path_right: str,
             caption: str, label: str,
             width_each: str = r"0.48\linewidth",
             placement: str = "ht") -> str:
    """Two side-by-side figures sharing a single caption."""
    lefts = []
    for p in (path_left, path_right):
        abs_path = ROOT / p
        if abs_path.exists():
            lefts.append(f"\\includegraphics[width={width_each}]{{{p}}}")
        else:
            lefts.append(
                f"\\parbox[c][3cm][c]{{{width_each}}}{{\\centering "
                f"\\fbox{{\\parbox[c][2.5cm][c]{{0.9\\linewidth}}{{"
                f"\\centering\\small\\itshape figure pending:\\\\"
                f"\\texttt{{{p}}}}}}}}}"
            )
    return "\n".join([
        f"\\begin{{figure}}[{placement}]",
        r"\centering",
        lefts[0],
        r"\hfill",
        lefts[1],
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        r"\end{figure}",
    ])


